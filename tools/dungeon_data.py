"""Writes Dungeon Timer's boss lists (DungeonTimerData.lua) from WoW Forever's own client table.

Reads DungeonEncounter for a build from wago.tools (product wowf): each dungeon's and raid's encounters, by instance
map, in the table's order. Encounters of one map that share a name are one boss with several encounter IDs (the client
keeps a set per difficulty, and WoW Forever added sets of its own). A boss takes its place from its newest encounter.
Season of Discovery's raid versions of dungeons (difficulties 198 and 215) only add their IDs to bosses the dungeon
has; their own encounters are left out.

Usage: python -I tools/dungeon_data.py [--build 1.60.1.71037] [--cache DIR]
"""
import argparse
import collections
import csv
import io
import json
import time
import urllib.request
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent
OUT = PROJECT / 'HastesSuperTweaks' / 'Modules' / 'DungeonTimerData.lua'
AGENT = {'User-Agent': 'Mozilla/5.0 (dungeon_data.py)'}

# Difficulties whose encounters aren't bosses of their own: Season of Discovery's raid versions of dungeons.
ALIAS_ONLY = {198, 215}
# Maps that aren't instances to time: 0 holds a retired row, 2720 a test boss.
SKIP_MAPS = {0, 2720}
# Encounters that aren't a boss: 3018 "The Molten Core" comes after Ragnaros and would be taken for the final boss.
SKIP_ENCOUNTERS = {3018}
# The same boss spelled another way in another difficulty's row.
SAME_BOSS = {'Gelihast': 'Geilhast'}
# Instances whose final boss isn't the table's last, by map. The run is done when the last boss listed dies, and the
# Sunken Temple's table ends with Jammal'an the Prophet, who dies before the dragons and the Shade of Eranikus.
FINAL_BOSS = {109: 'Shade of Eranikus'}


def fetch(url):
    for attempt in range(4):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=AGENT), timeout=120) as r:
                return r.read().decode('utf-8')
        except OSError:
            if attempt == 3:
                raise
            time.sleep(2 * (attempt + 1))


def latest_build():
    return json.loads(fetch('https://wago.tools/api/builds'))['wowf'][0]['version']


def table(cache, build, name):
    path = cache / f'{name}-{build}.csv'
    if not path.exists():
        path.write_text(fetch(f'https://wago.tools/db2/{name}/csv?product=wowf&build={build}'), encoding='utf-8')
    return list(csv.DictReader(io.StringIO(path.read_text(encoding='utf-8'))))


def bosses(rows):
    """{map: [(name, [encounter IDs, lowest first])]}, each map's bosses in order."""
    maps = collections.defaultdict(dict)
    for row in sorted(rows, key=lambda r: int(r['ID'])):
        instance, name = int(row['MapID']), row['Name_lang'].strip()
        if instance in SKIP_MAPS or int(row['ID']) in SKIP_ENCOUNTERS or not name:
            continue
        name = SAME_BOSS.get(name, name)
        alias = int(row['DifficultyID']) in ALIAS_ONLY
        boss = maps[instance].get(name)
        if not boss:
            if alias:
                continue
            boss = maps[instance][name] = {'ids': [], 'order': 0, 'newest': 0}
        boss['ids'].append(int(row['ID']))
        if not alias:
            boss['order'], boss['newest'] = int(row['OrderIndex']), int(row['ID'])
    # A second pass for the alias rows that came before their boss's own row.
    for row in rows:
        instance, name = int(row['MapID']), SAME_BOSS.get(row['Name_lang'].strip(), row['Name_lang'].strip())
        boss = maps.get(instance, {}).get(name)
        if boss and int(row['ID']) not in SKIP_ENCOUNTERS and int(row['ID']) not in boss['ids']:
            boss['ids'].append(int(row['ID']))
    result = {}
    for instance, found in maps.items():
        final = FINAL_BOSS.get(instance)
        assert final is None or final in found, instance
        ordered = sorted(found.items(), key=lambda item: (item[0] == final, item[1]['order'], item[1]['newest']))
        result[instance] = [(name, sorted(boss['ids'])) for name, boss in ordered]
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--build', help='a wowf build such as 1.60.1.71037 (default: the newest)')
    parser.add_argument('--cache', default=str(PROJECT / '.cache' / 'dungeon_data'))
    args = parser.parse_args()
    build = args.build or latest_build()
    cache = Path(args.cache)
    cache.mkdir(parents=True, exist_ok=True)
    data = bosses(table(cache, build, 'DungeonEncounter'))
    lines = [
        '-- Dungeon Timer\'s boss lists: each dungeon\'s and raid\'s bosses in order, by instance map ID.',
        f'-- Generated by tools/dungeon_data.py from the game\'s DungeonEncounter table, build {build}. Run the script',
        '-- again after a patch instead of editing this file.',
        '-- A map\'s bosses: "encounterID,encounterID=Name;..." (a boss the game has several encounters for lists them all).',
        '-- Kept as text and read only when you enter that instance (DungeonTimer.lua).',
        '-- SPDX-License-Identifier: MPL-2.0',
        'local ADDON, ns = ...',
        'ns.DungeonBosses = {',
        f'    build = "{build}",',
    ]
    total = 0
    for instance in sorted(data):
        text = ';'.join(','.join(map(str, ids)) + '=' + name for name, ids in data[instance])
        assert not any(c in name for name, _ in data[instance] for c in ';="\\'), instance
        lines.append(f'    [{instance}] = "{text}",')
        total += len(data[instance])
    lines.append('}')
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f'Wrote {total} bosses in {len(data)} instances from build {build} to {OUT.relative_to(PROJECT)}')


if __name__ == '__main__':
    main()
